def whole_boxes(product_id, qty):
    """Сколько ЦЕЛЫХ коробок в количестве — только если делится без остатка.

    Иначе None: в документах и сводках пишем просто штуки (просьба владельца
    16.08.2026 — «2 кор / 170 шт» путает людей, 170 штук это не две коробки;
    общий итог по коробкам и россыпи стоит внизу документа).
    """
    p = BY_ID.get(product_id)
    if p is None:
        return None
    try:
        per_box, qty = int(p["box"]), int(qty)
    except (TypeError, ValueError, KeyError):
        return None
    if per_box <= 0 or qty <= 0 or qty % per_box:
        return None
    return qty // per_box


def _base_name(name: str) -> str:
    """Имя товара без пояснения в скобках: «БУТАСТИМ (бутафосфан…)» → «бутастим»."""
    return str(name or "").split("(")[0].strip().lower()


def _name_words(s: str) -> list:
    """Слова короткого имени, дефис — тоже разделитель: «альтопен-форте» =
    «альтопен форте», «тривитоп» — начало «тривитоп-ad3e»."""
    return [w for w in re.split(r"[\s\-]+", s) if w]


def _vol_key(volume: str) -> str:
    """Фасовка без пробелов и пояснений: «100 мл», «100мл», «100 мл.» —
    одно и то же; «10 мл (10 фл)» = «10 мл» (ревизия 06.09.2026: пачка
    Окситопа/Энротопа не находилась по «10 мл», накладная проводилась без
    списания остатка)."""
    v = re.sub(r"\([^)]*\)", "", str(volume or ""))
    v = re.sub(r"\s+", "", v.strip().lower()).rstrip(".")
    return v.replace("ml", "мл")


def match_product(name: str, volume: str):
    """Находит товар прайса по названию и фасовке.

    Цепочка: точное имя+фасовка → нечёткое полное имя → КОРОТКОЕ имя без
    скобок при точной фасовке → опечатка в коротком имени. Последние две
    ступени добавлены 18.08.2026: владелец задавал спеццены списком
    («Бутастим 100 мл 420»), и короткие имена не дотягивали до порога —
    бот отвечал «ни один товар не распознан».
    """
    name_l = (name or "").strip().lower()
    vol_l = (volume or "").strip().lower()
    for p in PRICE_LIST_DATA:
        if p["name"].lower() == name_l and p["volume"].lower() == vol_l:
            return p
    base, vkey = _base_name(name), _vol_key(volume)
    same_vol = [p for p in PRICE_LIST_DATA if _vol_key(p["volume"]) == vkey] \
        if base and vkey else []
    # ТОЧНОЕ короткое имя + точная фасовка — РАНЬШЕ нечёткого поиска по
    # полной строке (ревизия 27.08.2026: difflib находил «альтопен | 100 мл»
    # ≈ «кальфотон | 100 мл» с 0.857 и продавал чужой товар).
    exact_base = [p for p in same_vol if _base_name(p["name"]) == base]
    if len(exact_base) == 1:
        return exact_base[0]
    if exact_base:
        return None                      # двусмысленно — не гадаем
    # Имя, которое ТОЧНО существует в прайсе, но с ДРУГИМИ фасовками, не
    # «дочиниваем» нечёткими ступенями до чужого товара: «Альтопен 200 мл»
    # не должен стать АЛЬТОПЕРОМ, а «Сурфагон Ультра 10 мкг 20 мл» —
    # СУРФАГОНОМ 50 мкг (другая дозировка!). Такой фасовки просто нет.
    if base and any(_base_name(p["name"]) == base for p in PRICE_LIST_DATA):
        return None
    # Короткое имя — НАЧАЛО имени товара по словам («Докцилин» ⊂ «ДОКЦИЛИН
    # 200», «Цефти» ⊂ «ЦЕФТИ DC») при точной фасовке — единственный
    # кандидат принимается, несколько — не гадаем (ревизия 06.09.2026).
    if base and vkey:
        bw = _name_words(base)
        eq = [p for p in same_vol if _name_words(_base_name(p["name"])) == bw]
        if len(eq) == 1:
            return eq[0]                 # «Альтопен форте» = АЛЬТОПЕН-ФОРТЕ
        pref = [p for p in same_vol
                if _name_words(_base_name(p["name"]))[:len(bw)] == bw]
        if len(pref) == 1:
            return pref[0]
        if pref:
            return None
    # Опечатка в коротком имени при точной фасовке — РАНЬШЕ нечёткого
    # поиска по полной строке (ревизия 06.09.2026: «Альтопён 100 мл» по
    # полной строке уезжал в КАЛЬФОТОН — хвост « | 100 мл» тянул сходство).
    scored = []
    if base and vkey:
        scored = sorted(
            ((difflib.SequenceMatcher(None, base, _base_name(p["name"])).ratio(), p)
             for p in same_vol), key=lambda x: -x[0])
    # Берём только уверенного и явного лидера: «Клозатоп» не должен
    # превратиться в «Клозатоп-Форте», а «Топмектин» — в «Топмектин гель».
    if scored and scored[0][0] >= 0.86 and (
            len(scored) == 1 or scored[0][0] - scored[1][0] >= 0.08):
        return scored[0][1]
    m = difflib.get_close_matches(f"{name_l} | {vol_l}", list(_KEYS), n=1, cutoff=0.85)
    if m:
        cand = _KEYS[m[0]]
        # Полная строка совпала, но по короткому имени этот товар — не
        # ближайший среди товаров той же фасовки (или совсем не похож):
        # это хвост фасовки тянет сходство к чужому товару. Не подставляем.
        if base:
            r_cand = difflib.SequenceMatcher(
                None, base, _base_name(cand["name"])).ratio()
            best = max((s for s, _p in scored), default=0.0)
            if r_cand < 0.7 or r_cand < best:
                return None
        return cand
    return None
